const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

function buildVariant(
  family: Family,
  spec: VariantSpec,
  index: number,
): ProductVariantSeed | undefined {
  switch (family.variantKind) {
    case "Clothing":
      return { kind: "Clothing", size: spec.size ?? "M", color: spec.color ?? CLOTHING_COLORS[index % 5] };
    case "Shoe":
      return { kind: "Shoe", size: spec.size ?? "Size_42", color: spec.color ?? SHOE_COLORS[index % 5] };
    case "Accessory":
      return { kind: "Accessory", color: spec.color ?? CLOTHING_COLORS[index % 5] };
    case "Decor":
      return { kind: "Decor", color: spec.color ?? "Bronze" };
    default:
      return undefined;
  }
}

function expand(): ProductSeed[] {
  const out: ProductSeed[] = [];
  let counter = 0;

  for (const family of families) {
    family.variants.forEach((spec, index) => {
      counter += 1;
      const name = `${family.name} ${spec.label}`;
      const slug = `${family.key}-${spec.suffix}`;
      const price = Math.round((family.basePrice + spec.priceDelta) * 100) / 100;

      // Ratings and review counts are derived from the slug so they are stable
      // across reseeds rather than jittering on every run.
      const hash = [...slug].reduce((acc, char) => acc + char.charCodeAt(0), 0);
      const rating = Math.round((3.8 + (hash % 12) / 10) * 10) / 10;
      const reviewCount = 4 + (hash % 220);

      const categories = [...family.categories];
      // Everything from the last two families reads as a recent addition.
      if (index === 0 && counter % 7 === 0) categories.push("new-arrival");

      out.push({
        slug,
        name,
        imagePool: family.key,
        brand: family.brand,
        sku: `MER-${slugify(family.key).toUpperCase().slice(0, 6)}-${String(counter).padStart(3, "0")}`,
        price,
        categories,
        tags: family.tags,
        material: family.material,
        rating,
        reviewCount,
        inStock: spec.inStock ?? true,
        shortDescription: family.shortDescription,
        description: [...family.body, "## This version", spec.note],
        variant: buildVariant(family, spec, index),
        seo: {
          title: `${name} | Meridian`,
          description: family.shortDescription.slice(0, 155),
        },
        es: {
          name: `${family.esName} ${spec.label}`,
          shortDescription: family.esShortDescription,
        },
      });
    });
  }

  return out;
}

export const products: ProductSeed[] = expand();

